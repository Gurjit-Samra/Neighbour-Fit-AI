async function seedCsv() {
  console.log("Seeding 185 CSV neighbourhoods...");
  let inserted = 0;
  let skipped = 0;
  for (const n of CSV_NEIGHBOURHOODS) {
    const existing = await db
      .select({ id: neighborhoodsTable.id })
      .from(neighborhoodsTable)
      .where(eq(neighborhoodsTable.slug, n.slug))
      .limit(1);
    if (existing.length === 0) {
      await db.insert(neighborhoodsTable).values(n as any);
      console.log(`  Inserted: ${n.name}`);
      inserted++;
    } else {
      skipped++;
    }
  }
  console.log(`Seed complete: ${inserted} inserted, ${skipped} skipped.`);
  process.exit(0);
}

seedCsv().catch((err) => {
  console.error("Seed failed:", err);
  process.exit(1);
});
